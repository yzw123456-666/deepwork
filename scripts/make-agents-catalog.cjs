async function githubPublish() {
  const token = process.env.GITHUB_TOKEN
  if (!token) { console.log('[skip] 无 GITHUB_TOKEN，跳过 GitHub 上传'); return }
  const repo = 'yzw123456-666/deepwork'
  const auth = { Authorization: `Bearer ${token}`, 'User-Agent': 'deepwork-release', Accept: 'application/vnd.github+json' }
  // 用最新 release（v26.9.66+）；没有则报错提示先发版
  const rels = await fetch(`https://api.github.com/repos/${repo}/releases?per_page=1`, { headers: auth }).then(r => r.json())
  const rel = Array.isArray(rels) ? rels[0] : null
  if (!rel?.id) throw new Error('未找到任何 release，请先发布一个版本')
  const name = 'agents.json'
  // 已存在同名 asset 则先删
  for (const a of rel.assets || []) {
    if (a.name === name) {
      await fetch(`https://api.github.com/repos/${repo}/releases/assets/${a.id}`, { method: 'DELETE', headers: auth })
      console.log('  已删除旧 asset:', name)
    }
  }
  const buf = fs.readFileSync(OUT)
  const up = await fetch(`https://uploads.github.com/repos/${repo}/releases/${rel.id}/assets?name=${name}`, {
    method: 'POST', headers: { ...auth, 'Content-Type': 'application/json' }, body: buf,
  }).then(r => r.json())
  if (!up.browser_download_url) throw new Error('GitHub 上传失败: ' + JSON.stringify(up).slice(0, 200))
  console.log('  GitHub:', up.browser_download_url)
}

async function finalosPublish() {
  const token = process.env.FINALOS_TOKEN
  const osid = process.env.FINALOS_OSID
  if (!token || !osid) { console.log('[skip] 无文汇百川凭证，跳过'); return }
  const API = 'https://api.publicos.cn/api/web'
  const buf = fs.readFileSync(OUT)
  const form = new FormData()
  form.append('token', token)
  form.append('file', new Blob([buf]), 'agents.json')
  form.append('filename', 'agents.json')
  form.append('path', 'deepwork-update')
  const res = await fetch(`${API}/file2url?osid=${encodeURIComponent(osid)}`, { method: 'POST', body: form })
  const j = await res.json()
  if (j.code !== 0) throw new Error('文汇百川上传失败: ' + JSON.stringify(j).slice(0, 200))
  console.log('  文汇百川:', j.url)
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true })
  const catalog = {
    updatedAt: new Date().toISOString().slice(0, 10),
    agents: CATALOG,
  }
  fs.writeFileSync(OUT, JSON.stringify(catalog, null, 2), 'utf-8')
  console.log(`✅ 清单已生成: ${OUT}（${CATALOG.length} 个插件）`)

  if (process.argv.includes('--publish')) {
    console.log('上传 GitHub Releases…')
    await githubPublish()
    console.log('上传文汇百川…')
    await finalosPublish()
    console.log('✅ 双线路发布完成')
  }
}

main().catch(e => { console.error('失败:', e.message); process.exit(1) })
